#!/usr/bin/env python3
"""Build the pinned, static Twemoji pack and a compact Unicode sequence trie.

Usage: python3 tools/build_emoji.py build/twemoji-17.0.2.zip
Source: https://codeload.github.com/jdecked/twemoji/zip/refs/tags/v17.0.2
Pillow with WebP support is needed only to regenerate these checked-in assets.
"""
import hashlib
import io
import struct
import sys
import zipfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE_SHA = '3be4944db98517127099c00ad0abd2469a78f797c4f30cd40570b1ffd8d898e4'
archive = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(archive).hexdigest() == SOURCE_SHA, 'Twemoji archive checksum'
z = zipfile.ZipFile(io.BytesIO(archive))
items = sorted(n for n in z.namelist() if '/assets/72x72/' in n and n.endswith('.png'))
assert len(items) == 4009
blobs = []
for name in items:
    im = Image.open(io.BytesIO(z.read(name))).convert('RGBA').resize((32, 32), Image.Resampling.LANCZOS)
    buf = io.BytesIO(); im.save(buf, format='WEBP', lossless=True, method=6, exact=True)
    blobs.append(buf.getvalue())
# Each record is indexed in the executable; no full pack/index is loaded into RAM.
# Header: magic, artwork count, payload SHA256. Cache identities use this digest.
payload = b''.join(blobs)
digest = hashlib.sha256(payload).digest()
pack = b'STEMOJI1' + struct.pack('<I', len(items)) + digest + payload
(ROOT / 'assets/emoji.pack').write_bytes(pack)
nodes = [{'edges': {}, 'emoji': -1}]
for index, name in enumerate(items):
    points = tuple(int(cp, 16) for cp in Path(name).stem.split('-'))
    for sequence in {points, tuple(cp for cp in points if cp != 0xfe0f)}:
        node = 0
        for cp in sequence:
            if cp not in nodes[node]['edges']:
                nodes[node]['edges'][cp] = len(nodes)
                nodes.append({'edges': {}, 'emoji': -1})
            node = nodes[node]['edges'][cp]
        assert nodes[node]['emoji'] in (-1, index), 'Ambiguous Unicode sequence'
        nodes[node]['emoji'] = index
edges = []
node_lines = []
for node in nodes:
    node_lines.append(f'{{{len(edges)},{len(node["edges"])},{node["emoji"]}}},')
    edges.extend(sorted(node['edges'].items()))
assert len(nodes) < 65536 and len(edges) < 65536
lines = ['/* Generated by tools/build_emoji.py; Twemoji 17.0.2, Unicode 17. */',
         f'#define ST_EMOJI_COUNT {len(items)}', f'#define ST_EMOJI_PACK_BYTES {len(pack)}u',
         f'#define ST_EMOJI_DIGEST "{digest.hex()}"',
         'static const unsigned char emoji_digest[32] = {' + ','.join(str(b) for b in digest) + '};',
         'typedef struct { uint16_t first,count;int16_t emoji; } EmojiNode;',
         'typedef struct { uint32_t cp;uint16_t child; } EmojiEdge;',
         'typedef struct { uint32_t offset,length; } EmojiRecord;',
         'static const EmojiNode emoji_nodes[] = {', *node_lines, '};',
         'static const EmojiEdge emoji_edges[] = {']
lines.extend(f'{{0x{cp:x},{child}}},' for cp, child in edges)
lines += ['};', 'static const EmojiRecord emoji_records[] = {']
offset = 44
for blob in blobs:
    lines.append(f'{{{offset},{len(blob)}}},'); offset += len(blob)
lines += ['};', '']
(ROOT / 'include/emoji_data.h').write_text('\n'.join(lines))
for src, dest in [('LICENSE', 'TWEMOJI-CODE.txt'), ('LICENSE-GRAPHICS', 'TWEMOJI-GRAPHICS.txt')]:
    (ROOT / 'licenses' / dest).write_bytes(z.read('twemoji-17.0.2/' + src))
(ROOT / 'licenses/TWEMOJI-NOTICE.txt').write_text(
    'Static emoji artwork: Twemoji 17.0.2, by Twitter, Inc. and other contributors.\n'
    'https://github.com/jdecked/twemoji/tree/v17.0.2\n'
    'Artwork licensed CC BY 4.0: https://creativecommons.org/licenses/by/4.0/\n'
    'Adapted from 72x72 PNG to 32x32 lossless WebP for the PSP client.\n'
    'Source archive SHA256: ' + SOURCE_SHA + '\n'
    'Pack payload SHA256: ' + digest.hex() + '\n')
print(f'Twemoji pack: {len(items)} static images, {len(pack):,} bytes, {len(nodes)} trie nodes')
