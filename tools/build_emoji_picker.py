#!/usr/bin/env python3
"""Reverse the pinned emoji trie without changing emoji.pack or its indexes."""
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
source = (root / 'include/emoji_data.h').read_text()
nodes_text = source.split('emoji_nodes[] = {', 1)[1].split('};', 1)[0]
edges_text = source.split('emoji_edges[] = {', 1)[1].split('};', 1)[0]
nodes = [tuple(map(int, x)) for x in re.findall(r'\{(\d+),(\d+),(-?\d+)\}', nodes_text)]
edges = [tuple(int(v, 0) for v in x) for x in re.findall(r'\{(0x[0-9a-fA-F]+|\d+),(\d+)\}', edges_text)]
count = int(re.search(r'ST_EMOJI_COUNT (\d+)', source)[1])
texts = [None] * count

def walk(node, path):
    first, size, index = nodes[node]
    if index >= 0:
        value = ''.join(chr(cp) for cp in path)
        if texts[index] is None or len(value) < len(texts[index]):
            texts[index] = value
    for cp, child in edges[first:first+size]:
        walk(child, path + [cp])

walk(0, [])
assert all(texts)
lines = ['/* Generated by tools/build_emoji_picker.py from the pinned trie. */',
         'static const char *const emoji_texts[] = {']
lines += ['"' + ''.join(f'\\x{b:02x}' for b in text.encode()) + '",' for text in texts]
lines.append('};')
(root / 'include/emoji_picker_data.h').write_text('\n'.join(lines) + '\n')
print(f'Generated {count} Unicode emoji picker entries; pack unchanged.')
