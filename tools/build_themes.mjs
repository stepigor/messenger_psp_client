// Generate with @material/material-color-utilities 0.3.0, as pinned by Stoat 0.15.1.
// node tools/build_themes.mjs /path/to/material-color-utilities/index.js
import {pathToFileURL} from 'node:url';
import {writeFileSync} from 'node:fs';
const {Hct,SchemeTonalSpot,argbFromHex}=await import(pathToFileURL(process.argv[2]));
const seeds=['#FF5733','#ffdc2f','#9bf088','#54ecc1','#549bec','#5470ec','#8C5FD3'];
// Order matches StThemeColors. PSP framebuffer uses ABGR, not ARGB.
const roles=['onSurface','onSurfaceVariant','primary','surface','surfaceContainerLowest',
  'surfaceContainerLow','surfaceContainerHigh','outlineVariant','secondaryContainer',
  'surfaceContainerHighest','onSurface'];
const abgr=v=>`0x${((0xff000000|((v&255)<<16)|(v&0xff00)|((v>>16)&255))>>>0).toString(16)}u`;
let out='/* Generated by tools/build_themes.mjs; MCU 0.3.0, Tonal Spot, contrast 0. */\n';
const brand=['0xfff4e9dcu','0xffcdbba6u','0xffffc99bu','0xff231810u','0xff1d130cu','0xff2e2016u','0xff422f20u','0xff594636u','0xff61462du','0xff503b29u','0xfff4e9dcu'];
const colours=(seed,dark)=>dark&&seed===seeds[4]?brand:roles.map(k=>abgr(new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)),dark,0)[k]));
out+=`#define ST_THEME_DEFAULT {${brand.join(',')}}\n`;
out+='static const StThemeColors palettes[2][ST_THEME_COLORS] = {\n';
for(const dark of [false,true]){
  out+='    {\n';
  for(const seed of seeds){const label=dark&&seed===seeds[4]?seed+"; brand background #101823":seed;
    out+=`        {${colours(seed,dark).join(',')}}, /* ${label} */\n`;}
  out+='    },\n';
}
out+='};\n';
writeFileSync(new URL('../include/theme_data.h',import.meta.url),out);
